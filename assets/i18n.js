export function normalizeLang(value) {
  return String(value || '').toLowerCase().startsWith('ar') ? 'ar' : 'en';
}

export function t(lang, key, vars) {
  const table = MESSAGES[normalizeLang(lang)] || MESSAGES.ar;
  let text = table[key];
  if (text === undefined) text = MESSAGES.ar[key];
  if (text === undefined) text = key;
  if (vars) {
    text = text.replace(/\{(\w+)\}/g, (match, name) => (vars[name] === undefined ? match : String(vars[name])));
  }
  return text;
}

/** يطبّق النصوص الثابتة (data-i18n) ويعيّن اللغة والاتجاه على الصفحة. */
export function translateDocument(lang) {
  const language = normalizeLang(lang);
  document.documentElement.lang = language;
  document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
  for (const element of document.querySelectorAll('[data-i18n]')) {
    element.textContent = t(language, element.dataset.i18n);
  }
  for (const element of document.querySelectorAll('[data-i18n-title]')) {
    element.title = t(language, element.dataset.i18nTitle);
  }
  for (const element of document.querySelectorAll('[data-i18n-placeholder]')) {
    element.placeholder = t(language, element.dataset.i18nPlaceholder);
  }
  for (const element of document.querySelectorAll('[data-i18n-content]')) {
    element.setAttribute('content', t(language, element.dataset.i18nContent));
  }
  for (const element of document.querySelectorAll('[data-i18n-aria-label]')) {
    element.setAttribute('aria-label', t(language, element.dataset.i18nAriaLabel));
  }
  return language;
}
